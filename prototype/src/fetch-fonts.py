#!/usr/bin/env python3
"""Download the prototype's typefaces once and vendor them locally.

The samples must look identical on a machine with no network and no
display server, so the woff2 files live next to them and each variant
carries its own @font-face rules.

    python3 prototype/src/fetch-fonts.py
"""

import pathlib
import re
import urllib.request

SRC = pathlib.Path(__file__).resolve().parent
FONT_DIR = SRC.parent / "fonts"
CSS_OUT = SRC / "styles" / "fonts.css"

# UA that makes the CSS API hand back woff2 rather than ttf.
UA = ("Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) "
      "Chrome/121.0.0.0 Safari/537.36")

FAMILIES = [
    # The sans stack is deliberately a system stack (Tahoma / Segoe UI), as the
    # real app will be. Mono is vendored so addresses and console output look
    # the same everywhere.
    ("IBM Plex Mono", "wght@400;500;600", "IBMPlexMono"),
]

# Latin covers everything the prototype sets in these faces; CJK falls
# through to the system stack, which is what the real app will do too.
LATIN_MARKER = "U+0000-00FF"


def fetch(url: str) -> bytes:
    req = urllib.request.Request(url, headers={"User-Agent": UA})
    with urllib.request.urlopen(req, timeout=60) as r:
        return r.read()


def main() -> int:
    FONT_DIR.mkdir(parents=True, exist_ok=True)
    faces = []

    for family, spec, slug in FAMILIES:
        api = (f"https://fonts.googleapis.com/css2?family={family.replace(' ', '+')}"
               f":{spec}&display=swap")
        css = fetch(api).decode("utf-8")
        blocks = re.findall(r"@font-face\s*\{(.*?)\}", css, re.S)
        kept = 0
        for block in blocks:
            if LATIN_MARKER not in block:
                continue
            weight = re.search(r"font-weight:\s*(\d+)", block).group(1)
            url = re.search(r"url\((https://[^)]+\.woff2)\)", block).group(1)
            name = f"{slug}-{weight}.woff2"
            target = FONT_DIR / name
            if not target.exists():
                target.write_bytes(fetch(url))
            faces.append((family, weight, name, target.stat().st_size))
            kept += 1
        print(f"{family:16s} latin faces kept: {kept}")

    lines = [
        "/* Generated by src/fetch-fonts.py — do not edit by hand.",
        "   Vendored so the samples render identically offline. */",
    ]
    for family, weight, name, _ in faces:
        lines.append(
            "@font-face{font-family:'%s';font-style:normal;font-weight:%s;"
            "font-display:swap;src:url('fonts/%s') format('woff2');}" % (family, weight, name)
        )
    CSS_OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")

    total = sum(size for *_, size in faces)
    print(f"\n{len(faces)} faces, {total // 1024} KiB total")
    print(f"wrote {CSS_OUT.relative_to(SRC.parent.parent)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
